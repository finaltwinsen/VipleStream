/**
 * @file src/vr/vr_ipc_abi_table.h
 * @brief VipleStream §VR（M1b S1-06／S1-18，selftest T6）：vr_ipc_abi.h 的 sizeof／alignof／offsetof 對照表。
 *
 * server（MinGW GCC）與 vr_probe（MSVC）**include 同一份表**，各自以自己的編譯器算出數值後逐列印出，
 * selftest T6 逐字比對兩邊的輸出：任何一列不同，就代表兩個編譯器對同一份 ABI 的版面理解不同
 * （或 vr_probe 是以舊版標頭建出來的），IPC 不可上線。
 *
 * 列的格式固定為 `<key>=<十進位值>`，不含空白：
 *   - `const.<巨集>`：版號、magic、各種容量常數（抓「vr_probe 用了舊標頭」）
 *   - `size.<型別>`、`align.<型別>`：sizeof／alignof
 *   - `off.<型別>.<欄位>`：offsetof（每個欄位都列，包含 reserved／pad）
 * vr_probe 的輸出行：`[VIPLE-VR-PROBE] abi-row <key>=<value>`，最後一行
 * `[VIPLE-VR-PROBE] abi-rows count=<n> digest=<16 位十六進位>`（digest 見 table_digest()）。
 *
 * 規則：
 *   - 這份表由 vr_ipc_abi.h 機械產生（每個 typedef struct 的每個欄位）；ABI 加欄位時一起更新，
 *     漏列的欄位不會被比對到。
 *   - 只依賴標準函式庫，MSVC `/W4 /WX /permissive-` 與 GCC `-Wall -Wextra` 都要能乾淨編譯。
 *   - 只在 x64 有意義（vr_ipc_abi.h 本身在非 x64 會 #error），所以只在 Windows 程式碼 include。
 */
