  inline constexpr std::size_t k_row_count = sizeof(k_rows) / sizeof(k_rows[0]);

  /// 一列的文字：`<key>=<value>`（不含換行）
  inline std::string format_row(const row_t &row) {
    return std::string(row.key) + "=" + std::to_string(row.value);
  }

  /// 全表的 FNV-1a 64：依序對每列的 `<key>=<value>\n` 取雜湊
  inline std::uint64_t table_digest() {
    std::uint64_t h = 1469598103934665603ull;
    for (const auto &row : k_rows) {
      const std::string line = format_row(row) + "\n";
      for (const unsigned char c : line) {
        h ^= c;
        h *= 1099511628211ull;
      }
    }
    return h;
  }
